# ---- 6) Build classifier ---------------------------------------------
function ClassifyName([string]$name) {
  foreach ($r in $rules) {
    if ($name.Contains($r[0])) { return $r[1] }
  }
  return $null
}

# ---- 7) Load existing catalog and find new items ---------------------
Step 'Loading existing catalog…'
$existingRaw = Get-Content -Path $ExistingCatalog -Raw -Encoding UTF8
$existingObj = $existingRaw | ConvertFrom-Json
$existingMahla = $null
foreach ($p in $existingObj.PSObject.Properties) {
  if ($p.Name.Length -eq 6) { $existingMahla = $p.Value; break }
}
$existingNames = New-Object 'System.Collections.Generic.HashSet[string]'
foreach ($p in $existingMahla.PSObject.Properties) {
  foreach ($n in $p.Value) { [void]$existingNames.Add($n) }
}
Write-Host "    -> existing catalog has $($existingNames.Count) items"

# ---- 8) Classify normalized names ------------------------------------
Step 'Classifying new items by department…'
$byDept = @{}
$unmatched = New-Object 'System.Collections.Generic.List[string]'
foreach ($n in $normSet) {
  if ($existingNames.Contains($n)) { continue }
  $dept = ClassifyName $n
  if ($null -eq $dept) { $unmatched.Add($n); continue }
  if (-not $byDept.ContainsKey($dept)) { $byDept[$dept] = New-Object 'System.Collections.Generic.List[string]' }
  $byDept[$dept].Add($n)
}

# ---- 9) Cap by limit, write outputs ----------------------------------
$total = ($byDept.Values | ForEach-Object { $_.Count } | Measure-Object -Sum).Sum
Step "Classified $total new items into $($byDept.Count) departments. $($unmatched.Count) unmatched."

# Trim if over limit (proportional)
if ($total -gt $Limit) {
  $factor = $Limit / $total
  foreach ($k in @($byDept.Keys)) {
    $keep = [Math]::Max(1, [int]($byDept[$k].Count * $factor))
    if ($keep -lt $byDept[$k].Count) { $byDept[$k] = $byDept[$k].GetRange(0, $keep) }
  }
}

