# What it does:
#   1. Downloads the latest PriceFull file from Shufersal's public price
#      portal (https://prices.shufersal.co.il), which is mandated by the
#      Israeli price-transparency law.
#   2. Decompresses the .gz, parses the XML, and extracts unique product
#      names.
#   3. Normalizes each name (strips weight/size/brand suffixes).
#   4. Heuristically classifies each name into one of our 21 departments
#      using a keyword map (most-specific keywords first).
#   5. Compares against the existing products_by_department.json and
#      keeps only NEW products.
#   6. Writes _phase2_additions.json next to this script — review and
#      merge into the main catalog.
#
# Run from PowerShell (Win10/11 has the built-in shell):
#   cd C:\Users\topel\shared-shopping-test\tools
#   powershell -NoProfile -ExecutionPolicy Bypass -File .\fetch_shufersal_catalog.ps1
#
# Optional: -Limit N to cap how many new products to keep (default 1500).
# =====================================================================
