function Step($msg) { Write-Host ">>> $msg" -ForegroundColor Cyan }

# ---- 1) Locate the most-recent PriceFull file ------------------------
Step 'Locating latest PriceFull file on prices.shufersal.co.il…'
# catID=2 = PriceFull files; storeID=0 = list all stores
$listUrl = 'https://prices.shufersal.co.il/FileObject/UpdateCategory?catID=2&storeID=0'
$listing = Invoke-WebRequest -Uri $listUrl -UseBasicParsing
$gzUrl = ($listing.Links | Where-Object { $_.href -match '\.gz$' } | Select-Object -First 1).href
if (-not $gzUrl) { throw "Couldn't find a .gz link in the catalog listing." }
if ($gzUrl -notmatch '^https?://') { $gzUrl = "https://prices.shufersal.co.il/$gzUrl" }
Write-Host "    -> $gzUrl"

# ---- 2) Download + decompress to memory ------------------------------
Step 'Downloading and decompressing…'
$tmpGz = [IO.Path]::GetTempFileName() + '.gz'
Invoke-WebRequest -Uri $gzUrl -OutFile $tmpGz -UseBasicParsing
$gzStream = [IO.File]::OpenRead($tmpGz)
$decompressed = New-Object IO.MemoryStream
$gz = New-Object IO.Compression.GZipStream($gzStream, [IO.Compression.CompressionMode]::Decompress)
$gz.CopyTo($decompressed); $gz.Dispose(); $gzStream.Dispose()
Remove-Item $tmpGz -ErrorAction SilentlyContinue
$decompressed.Position = 0
$xml = New-Object Xml.XmlDocument
$xml.Load($decompressed)
$decompressed.Dispose()

# ---- 3) Extract unique item names ------------------------------------
Step 'Extracting product names…'
$names = New-Object 'System.Collections.Generic.HashSet[string]'
foreach ($node in $xml.SelectNodes('//Item/ItemName')) {
  $n = ($node.InnerText).Trim()
  if ($n) { [void]$names.Add($n) }
}
Write-Host "    -> $($names.Count) raw unique names"

# ---- 4) Normalize ----------------------------------------------------
Step 'Normalizing (strip size / brand / weight)…'
function Normalize([string]$s) {
  $t = $s
  # collapse whitespace
  $t = ($t -replace '\s+', ' ').Trim()
  # remove parenthetical clauses
  $t = $t -replace '\([^)]*\)', ''
  # remove weight/volume tails: " 250 גרם", " 1 ליטר", etc.
  $t = $t -replace '\s*\d+(\.\d+)?\s*(גרם|ק"ג|קג|מ"ל|ליטר|ל''|יח''?|יחיד[הת])\.?$', ''
  $t = $t -replace '\s*\d+(\.\d+)?\s*(גרם|ק"ג|קג|מ"ל|ליטר|ל''|יח'')\b', ''
  # strip lone trailing numbers
  $t = $t -replace '\s+\d+$', ''
  # squash trailing punctuation
  $t = $t -replace '[\-\,\.\s]+$', ''
  $t = ($t -replace '\s+', ' ').Trim()
  return $t
}
$normSet = New-Object 'System.Collections.Generic.HashSet[string]'
foreach ($n in $names) {
  $nm = Normalize $n
  if ($nm.Length -ge 3 -and $nm.Length -le 40) { [void]$normSet.Add($nm) }
}
Write-Host "    -> $($normSet.Count) normalized unique names"

